// ============================================================================
// HELPER FUNCTIONS
// ============================================================================

export function getElementById(id: string): ArchitecturalElement | undefined {
  return ALL_ELEMENTS.find(el => el.id === id);
}

export function getElementsByCategory(category: string): ArchitecturalElement[] {
  return ALL_ELEMENTS.filter(el => el.category === category);
}

export function getElementsByPeriod(period: string): ArchitecturalElement[] {
  return ALL_ELEMENTS.filter(el => el.periods.includes(period as any));
}

export function getElementsByRegion(region: string): ArchitecturalElement[] {
  return ALL_ELEMENTS.filter(el => el.regions.includes(region as any));
}

export function searchElements(query: string): ArchitecturalElement[] {
  const lowerQuery = query.toLowerCase();
  return ALL_ELEMENTS.filter(el =>
    el.name.toLowerCase().includes(lowerQuery) ||
    el.alternativeNames.some(name => name.toLowerCase().includes(lowerQuery)) ||
    el.searchTags.some(tag => tag.toLowerCase().includes(lowerQuery))
  );
}

export function getRandomElements(count: number, exclude: string[] = []): ArchitecturalElement[] {
  const available = ALL_ELEMENTS.filter(el => !exclude.includes(el.id));
  const shuffled = [...available].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

